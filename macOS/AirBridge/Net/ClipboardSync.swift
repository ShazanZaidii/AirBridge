import AppKit
import CryptoKit

/// Clipboard sync (§5, §5.1): text, images and files, local filters, echo suppression, no relaying.
@MainActor final class ClipboardSync {
    static let shared = ClipboardSync()

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var lastReceivedHash: Data?
    /// What this Mac last sent: the same text is never sent twice in a row (no clipboard ping-pong).
    private var lastSentHash: Data?

    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardSync.shared.poll() }
        }
    }

    /// Call after AirBridge itself writes to the pasteboard (e.g. received files) so it is not sent back out.
    func noteOwnWrite() { lastChangeCount = NSPasteboard.general.changeCount }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let types = pb.types ?? []
        guard !types.contains(where: ClipboardSync.skipTypes.contains) else { return }
        // Files win over text (a Finder copy also carries the names as text), text wins over an image (a spreadsheet range
        // carries both), §5.1.
        if types.contains(.fileURL) { sendFiles(from: pb); return }
        guard let text = pb.string(forType: .string), !text.isEmpty else {
            if types.contains(.png) || types.contains(.tiff) { sendImage(from: pb) }
            return
        }
        let h = ClipboardSync.hash(text)
        if h == lastReceivedHash || h == lastSentHash { return }
        guard ClipboardSync.passesFilters(text) else { return }
        guard text.utf8.count <= Proto.clipMaxBytes else {
            AppModel.shared.notice("Clipboard too large to sync (over 512 KB)")
            return
        }
        lastSentHash = h
        PeerManager.shared.broadcastClip(["t": "clip", "kind": "text", "text": text, "ts": Proto.nowMs()])
    }

    /// Called on the network queue for an incoming `clip`.
    nonisolated static func receive(_ msg: [String: Any], from peerId: String) {
        guard msg.str("kind") == "text", let text = msg.str("text"), !text.isEmpty,
              text.utf8.count <= Proto.clipMaxBytes else { return }
        onMain { ClipboardSync.shared.apply(text) }
    }

    private func apply(_ text: String) {
        lastReceivedHash = ClipboardSync.hash(text)
        lastSentHash = nil // something newer arrived: copying the old text again here is a real change
        let pb = NSPasteboard.general
        // Already there (the same copy again): don't rewrite the pasteboard.
        if pb.string(forType: .string) == text { return }
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChangeCount = pb.changeCount
    }

    /// Call after this Mac put a received picture on the clipboard, so it is not sent back out.
    func noteReceivedImage(_ png: Data) {
        lastReceivedHash = Data(SHA256.hash(data: png))
        lastSentHash = nil
        lastChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: Images and files (§5.1)

    private func notice(_ text: String) { AppModel.shared.notice(text) }

    private func sendFiles(from pb: NSPasteboard) {
        guard PeerManager.shared.anyClipMediaPeer(),
              let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
              !urls.isEmpty else { return }
        var files: [URL] = [], total: Int64 = 0, folders = 0
        for u in urls {
            let v = try? u.resourceValues(forKeys: [.isRegularFileKey, .isDirectoryKey, .fileSizeKey])
            if v?.isRegularFile == true { files.append(u); total += Int64(v?.fileSize ?? 0) }
            else if v?.isDirectory == true { folders += 1 }
        }
        guard !files.isEmpty else {
            if folders > 0 { notice("Folders can't go through the clipboard yet. Send them with AirBridge instead.") }
            return
        }
        guard files.count <= Proto.clipFilesMaxCount, total <= Int64(Proto.clipFilesMaxBytes) else {
            notice("Copied files are too big to sync (over 100 MB or 20 files)")
            return
        }
        let key = urls.map { u -> String in
            let v = try? u.resourceValues(forKeys: [.contentModificationDateKey, .fileSizeKey])
            return "\(u.path)|\(v?.fileSize ?? 0)|\(v?.contentModificationDate?.timeIntervalSince1970 ?? 0)"
        }.joined(separator: "\n")
        let h = ClipboardSync.hash(key)
        if h == lastReceivedHash || h == lastSentHash { return }
        lastSentHash = h
        PeerManager.shared.broadcastClipMedia(files, cleanup: {})
    }

    private func sendImage(from pb: NSPasteboard) {
        guard PeerManager.shared.anyClipMediaPeer() else { return }
        let png = pb.data(forType: .png), tiff = pb.data(forType: .tiff)
        Task.detached(priority: .utility) {
            var data = png
            if data == nil, let tiff { data = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) }
            guard let data, !data.isEmpty else { return }
            guard data.count <= Proto.clipImageMaxBytes else {
                await MainActor.run { ClipboardSync.shared.notice("That image is too big to sync (over 25 MB)") }
                return
            }
            let h = Data(SHA256.hash(data: data))
            guard let file = ClipboardInbox.outFile(named: "clipboard.png", data: data) else { return }
            await MainActor.run {
                let me = ClipboardSync.shared
                if h == me.lastReceivedHash || h == me.lastSentHash { ClipboardInbox.discard(file); return }
                me.lastSentHash = h
                PeerManager.shared.broadcastClipMedia([file]) { ClipboardInbox.discard(file) }
            }
        }
    }

    private static func hash(_ s: String) -> Data { Data(SHA256.hash(data: Data(s.utf8))) }

    private static func passesFilters(_ text: String) -> Bool {
        guard let data = UserDefaults.standard.data(forKey: "ClipboardFilters"),
              let filters = try? JSONDecoder().decode([ClipboardFilter].self, from: data) else { return true }
        for f in filters where !f.keyword.isEmpty {
            switch f.type {
            case .startsWith: if text.hasPrefix(f.keyword) { return false }
            case .endsWith: if text.hasSuffix(f.keyword) { return false }
            case .contains: if text.contains(f.keyword) { return false }
            }
        }
        return true
    }
}
